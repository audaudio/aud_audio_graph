// Copies the AUD_* constants of the ffigen bindings into a Dart file that
// imports nothing, so that the platform-neutral API can use them without
// dart:ffi reaching a web build (web-001).
//
// Usage: node scripts/generate-abi-constants.js <bindings> <output> [--check]
// With --check it writes nothing and exits with 1 when <output> is stale.

import { existsSync, readFileSync, writeFileSync } from 'fs';

const header = `// @license
// Copyright (c) Audanika. All Rights Reserved.
//
// Use of this source code is governed by terms that can be
// found in the LICENSE file in the root of this package.

// Generated by scripts/generate-abi-constants.js from the ffigen bindings.
// Do not edit; run the script after ffigen.

// ignore_for_file: constant_identifier_names
`;

export function generate(bindings) {
  const constant = /^const (int|String|double) (AUD_[A-Z0-9_]+) = (.+);$/gm;
  const lines = [...bindings.matchAll(constant)].map(
    ([, type, name, value]) => `const ${type} ${name} = ${value};`,
  );
  return `${header}\n${lines.join('\n')}\n`;
}

function main([bindingsPath, outputPath, mode]) {
  if (!bindingsPath || !outputPath) {
    console.error(
      'Usage: node scripts/generate-abi-constants.js <bindings> <output> [--check]',
    );
    process.exit(2);
  }
  const expected = generate(readFileSync(bindingsPath, 'utf8'));
  if (mode === '--check') {
    const actual = existsSync(outputPath) ? readFileSync(outputPath, 'utf8') : '';
    if (actual !== expected) {
      console.error(`${outputPath} is stale; run the script without --check`);
      process.exit(1);
    }
    console.log(`${outputPath} is up to date`);
    return;
  }
  writeFileSync(outputPath, expected);
  console.log(`Wrote ${outputPath}`);
}

main(process.argv.slice(2));
